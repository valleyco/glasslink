void render_clear(uint16_t rgb565)
{
    int w = 0;
    int h = 0;
    hal_display_get_size(&w, &h);
    /* Use fill_rect for whole panel */
    if (w > 0 && h > 0) {
        hal_display_fill_rect(0, 0, w, h, rgb565);
    }
}

int render_blit_rect(int x, int y, int w, int h, const uint16_t *rgb565)
{
    if (w <= 0 || h <= 0) {
        return -1;
    }
    if (!rgb565) {
        return -1;
    }
    hal_display_blit_rect_rgb565(x, y, w, h, rgb565);
    return 0;
}

int render_fill_rect(int x, int y, int w, int h, uint16_t rgb565)
{
    if (w <= 0 || h <= 0) {
        return -1;
    }
    hal_display_fill_rect(x, y, w, h, rgb565);
    return 0;
}

int render_draw_text(int x, int y, const uint8_t *text, size_t len, uint16_t color,
                     int scale)
{
    int cx;
    size_t i;

    if (!text || scale < 1 || scale > 2) {
        return -1;
    }
    cx = x;
    for (i = 0; i < len; i++) {
        uint8_t ch = text[i];
        const uint8_t *g;
        int row;
        int col;

        if (ch < 0x20 || ch > 0x7E) {
            continue;
        }
        g = FONT5X7[ch - 0x20];
        for (row = 0; row < 7; row++) {
            uint8_t bits = g[row];
            for (col = 0; col < 5; col++) {
                if (bits & (0x10 >> col)) {
                    int px = cx + col * scale;
                    int py = y + row * scale;
                    if (scale == 1) {
                        hal_display_fill_rect(px, py, 1, 1, color);
                    } else {
                        hal_display_fill_rect(px, py, scale, scale, color);
                    }
                }
            }
        }
        cx += 6 * scale; /* 5 px glyph + 1 px gap */
    }
    return 0;
}
